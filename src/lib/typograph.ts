/**
 * Минимальная экранная типографика для коротких текстов из данных
 * (промо, шаги процесса): неразрывные пробелы там, где перенос строки
 * ломает чтение в узкой колонке телефона.
 *  - перед тире: строка не начинается с «—»;
 *  - после слов из 1–2 букв и коротких предлогов (в, на, с, до, от, без,
 *    для, под, при…): не висят в конце строки;
 *  - между числом и единицей/знаком (500 ₽, 2,5 м, 8 %): не разрываются.
 * Только для обычного текста — HTML не разбирает.
 */
const NBSP = '\u00a0'

/* Подряд идущие короткие слова («и в на») пересекаются: пробел, съеденный
   первым совпадением, — начало следующего; второй проход их добирает */
const SHORT = /(^|[\s(«])([А-Яа-яЁёA-Za-z]{1,2}|без|для|под|над|при|про|изо|обо) /gi

export function typograph(text: string): string {
  return text
    .replace(/ (—|–)/g, `${NBSP}$1`)
    .replace(SHORT, `$1$2${NBSP}`)
    .replace(SHORT, `$1$2${NBSP}`)
    .replace(/(\d) (₽|%|м|мм|см|кг|г\.|дн)/g, `$1${NBSP}$2`)
}
