/** null / "true" (битые значения в БД) — скрываем, показывать нечего. */
export function formatTrim(trim: string | null | undefined): string {
  if (!trim) return ''
  const t = trim.trim()
  if (!t || t.toLowerCase() === 'true') return ''
  return TRIM_LABELS[t] ?? t
}
